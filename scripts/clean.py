#!/usr/bin/env python3
"""Explicit age-based cache cleanup. Never touches assets/, output/, or arbitrary work files."""
import argparse
import json
from pathlib import Path
import shutil
import time
from common import ROOT, treebytes

def candidates(older_hours):
    root = ROOT/'work/cache'
    if root.is_symlink():
        raise ValueError('Refuse symlink cache root')
    cutoff=time.time()-older_hours*3600
    result=[]
    for category in ['shots','audio','assets','compositions']:
        parent=root/category
        if parent.is_symlink(): raise ValueError('Refuse symlink category')
        for folder in parent.glob('*'):
            if folder.is_symlink() or not folder.is_dir(): continue
            marker=folder/'complete.json'
            if marker.is_file() and marker.stat().st_mtime<cutoff:
                # Content-addressed folders generated by this pipeline only.
                if len(folder.name)==64 and all(c in '0123456789abcdef' for c in folder.name):
                    if any(p.is_symlink() for p in folder.rglob('*')):
                        raise ValueError('Refuse cache entry containing symlink')
                    result.append(folder)
    return result

def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--older-hours',type=float,default=168)
    ap.add_argument('--apply',action='store_true',help='Delete listed completed cache entries; default is dry run')
    args=ap.parse_args()
    if args.older_hours<0: ap.error('Age must be nonnegative')
    for p in candidates(args.older_hours):
        print(json.dumps({'path':str(p.relative_to(ROOT)), 'bytes':treebytes(p), 'delete':args.apply}))
        if args.apply: shutil.rmtree(p)

if __name__=='__main__': main()
