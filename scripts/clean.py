#!/usr/bin/env -S uv run python
"""Lock-aware age-based cleanup of completed, unprotected regenerable caches only."""
import argparse
from contextlib import contextmanager
import fcntl
import json
from pathlib import Path
import re
import shutil
import os
import subprocess
from contextlib import ExitStack
import time
from common import ROOT, treebytes

@contextmanager
def production_lock():
    path = ROOT/'work/production.lock'
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.is_symlink():
        raise ValueError('Refuse symlink production lock')
    with ExitStack() as stack:
        handle = stack.enter_context(path.open('a'))
        for other in sorted((ROOT/'work').rglob('*render*.lock')):
            if other.is_symlink():
                raise ValueError('Refuse symlink render lock')
            stream = stack.enter_context(other.open('a'))
            try:
                fcntl.flock(stream, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError:
                raise RuntimeError('Render busy; cleanup skipped')
        try:
            fcntl.flock(handle, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            raise RuntimeError('Production busy; cleanup skipped')
        try:
            yield
        finally:
            fcntl.flock(handle, fcntl.LOCK_UN)

def reference_hashes(bases):
    """Stream references with ripgrep; large compiled geometry JSON never enters Python memory."""
    files = []
    for base in bases:
        root = ROOT/base
        if root.is_symlink():
            raise ValueError('Refuse symlink reference root')
        for path in root.rglob('*'):
            if path.is_symlink() and path.suffix in {'.json', '.jsonl', '.md'}:
                if not path.resolve().is_relative_to(ROOT.resolve()):
                    raise ValueError('Refuse external symlink reference')
            if path.is_file() and path.suffix in {'.json', '.jsonl', '.md'}:
                files.append(str(path))
    result = set()
    for start in range(0, len(files), 128):
        command = ['rg', '--no-config', '--text', '--no-filename', '--only-matching',
                   r'\b[0-9a-f]{64}\b', '--'] + files[start:start+128]
        process = subprocess.run(command, capture_output=True, text=True)
        if process.returncode not in {0, 1}:
            raise RuntimeError('Reference scan failed; cleanup skipped: ' + process.stderr)
        result.update(process.stdout.splitlines())
    return result


def referenced_keys():
    return reference_hashes(('output', 'config', 'docs', 'work/cache'))

def candidates(older_hours, only_keys=None):
    if older_hours < 0:
        raise ValueError('Age must be nonnegative')
    selected = None if only_keys is None else set(only_keys)
    if selected is not None and any(not re.fullmatch(r'[0-9a-f]{64}', key) for key in selected):
        raise ValueError('Only-key must be a complete lowercase SHA256 cache key')
    root = ROOT/'work/cache'
    if root.is_symlink():
        raise ValueError('Refuse symlink cache root')
    cutoff=time.time()-older_hours*3600
    protected = referenced_keys()
    result=[]
    for category in ['shots','compositions']:
        parent=root/category
        if parent.is_symlink(): raise ValueError('Refuse symlink category')
        for folder in parent.glob('*'):
            if folder.is_symlink() or not folder.is_dir(): continue
            if selected is not None and folder.name not in selected: continue
            if folder.name in protected: continue
            if any(p.name in {'.lock', '.protected'} for p in folder.rglob('*')): continue
            marker=folder/'complete.json'
            if marker.is_file() and max(marker.stat().st_mtime, (folder/'.last-used').stat().st_mtime if (folder/'.last-used').exists() else 0)<cutoff:
                # Content-addressed folders generated by this pipeline only.
                if len(folder.name)==64 and all(c in '0123456789abcdef' for c in folder.name):
                    if any(p.is_symlink() for p in folder.rglob('*')):
                        raise ValueError('Refuse cache entry containing symlink')
                    result.append(folder)
    return result

def qa_candidates(older_hours=168):
    """Only paired compressed images produced by qa_images; all external references pin them."""
    root = ROOT/'work/qa-images'
    if root.is_symlink():
        raise ValueError('Refuse symlink QA cache')
    refs = reference_hashes(('output', 'docs', 'work/cache'))
    result = []
    for marker in root.glob('*.json'):
        if marker.is_symlink() or not re.fullmatch(r'[0-9a-f]{64}', marker.stem):
            continue
        try:
            data = json.loads(marker.read_text())
            image = Path(data['qa_path'])
            if image.parent != root or image.stem != marker.stem or image.suffix not in {'.webp', '.jpg'}:
                continue
            if image.is_symlink() or not image.is_file():
                continue
            if marker.stem in refs or data['qa_sha256'] in refs:
                continue
            if max(marker.stat().st_mtime, image.stat().st_mtime) >= time.time()-older_hours*3600:
                continue
            from common import filehash
            if filehash(image) == data['qa_sha256']:
                result.extend([image, marker])
        except (ValueError, KeyError, OSError):
            continue
    return result

def cleanup(older_hours=720, apply=False, only_keys=None, task=None, pressure=False):
    """Serialize with production and retain locks, handoff references and failed work."""
    rows = []
    with production_lock():
        planned = candidates(older_hours, only_keys)
        if only_keys is None:
            planned += qa_candidates()
        # Legacy entries have no reliable task ownership: task filtering must fail closed.
        if task is not None:
            planned = [p for p in planned if p.is_dir() and (p/'ownership.json').is_file() and json.loads((p/'ownership.json').read_text()).get('task_id') == task]
        if pressure:
            planned.sort(key=lambda p: (0 if p.suffix in {'.webp', '.jpg', '.json'} else 1, -(treebytes(p) if p.is_dir() else p.stat().st_size)))
        # Recheck symlinks immediately before the deletion plan is persisted.
        for p in planned:
            if p.is_symlink() or any((ROOT/parent).is_symlink() for parent in p.relative_to(ROOT).parents):
                raise ValueError('Refuse symlink ancestor')
        audit = ROOT/'work/cleanup-reports'/str(time.time_ns())
        if apply:
            audit.mkdir(parents=True)
            (audit/'plan.json').write_text(json.dumps([str(p.relative_to(ROOT)) for p in planned]))
        for p in planned:
            row = {'path':str(p.relative_to(ROOT)), 'bytes':(treebytes(p) if p.is_dir() else p.stat().st_size), 'delete':False, 'reason':'unreferenced completed regenerable cache', 'lifecycle':'REUSABLE'}
            if apply:
                row['deleted_bytes'] = 0
                row['deleted_files'] = 0
                try:
                    owned = sorted(p.rglob('*')) if p.is_dir() else [p]
                    for file in owned:
                        if file.is_symlink():
                            raise ValueError('Refuse symlink during deletion')
                        if file.is_file():
                            size = file.stat().st_size
                            file.unlink()
                            row['deleted_bytes'] += size
                            row['deleted_files'] += 1
                    if p.is_dir():
                        for directory in sorted((f for f in owned if f.is_dir()), key=lambda f:len(f.parts), reverse=True):
                            directory.rmdir()
                        p.rmdir()
                    row['delete'] = True
                except (OSError, ValueError) as exc:
                    row['error'] = str(exc)
            rows.append(row)
            if apply:
                (audit/'result.json').write_text(json.dumps(rows, indent=2))
    return rows

def cleanup_npm_cache(apply=False):
    """Explicitly clear disposable npm download data, never installed modules."""
    target = ROOT/'work/npm-cache'
    with production_lock():
        if target.is_symlink() or any(p.is_symlink() for p in target.rglob('*')):
            raise ValueError('Refuse npm cache containing symlink')
        row = {'path': str(target.relative_to(ROOT)), 'bytes': treebytes(target),
               'delete': apply, 'kind': 'regenerable_npm_download_cache'}
        if apply and target.exists():
            shutil.rmtree(target)
        return [row]

def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--older-hours',type=float,default=720)
    ap.add_argument('--apply',action='store_true',help='Delete listed completed cache entries; default is dry run')
    ap.add_argument('--auto',action='store_true',help='Apply safe age-based cleanup before production; never bypass locks or references')
    ap.add_argument('--npm-cache-only', action='store_true',
                    help='Explicit disposable npm download cache only; leaves node_modules and media intact')
    ap.add_argument('--only-key', action='append', default=None,
                    help='Restrict eligible entries to this SHA256 key; repeat for multiple keys. Age, completion, locks, protections and references still apply')
    ap.add_argument('--dry-run', action='store_true')
    ap.add_argument('--task')
    ap.add_argument('--expired', action='store_true')
    ap.add_argument('--pressure', action='store_true')
    ap.add_argument('--report', action='store_true')
    args=ap.parse_args()
    if args.older_hours<0: ap.error('Age must be nonnegative')
    try:
        rows = (cleanup_npm_cache(args.apply and not args.dry_run) if args.npm_cache_only else
                cleanup(args.older_hours, (args.apply or args.auto) and not args.dry_run, args.only_key, args.task, args.pressure))
    except RuntimeError as exc:
        print(json.dumps({'status':'SKIPPED', 'reason':str(exc), 'deleted_bytes':0}))
        return
    if args.report:
        print(json.dumps({'status':'APPLIED' if (args.apply or args.auto) and not args.dry_run else 'DRY_RUN',
                          'candidates':len(rows), 'candidate_bytes':sum(r['bytes'] for r in rows),
                          'deleted_bytes':sum(r.get('deleted_bytes', 0) for r in rows),
                          'failures':[r for r in rows if 'error' in r]}))
    for row in rows:
        print(json.dumps(row))

if __name__=='__main__': main()
